#!/usr/bin/env node
// Rebuilds src/data/hrr-risks.js from NASA's Human Research Roadmap risk pages.
//   node tools/fetch-hrr.mjs [--cache <dir>]     (--cache keeps the downloaded pages and reuses them)
// Every rating cell on a risk page has its own id (for example tdMarsPlanetOpsLxC), so cells are read by id.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const IDS = [77, 78, 80, 81, 82, 84, 85, 88, 95, 96, 99, 100, 101, 105, 167, 168, 173, 175, 176, 177, 179, 180];
const CELLS = [
  ["LEO6mo", "leo", "short", "Short (<30 days)"],
  ["LEO1yr", "leo", "long", "Long (30 days-1 year)"],
  ["DSS", "lunarOrbit", "short", "Short (<30 days)"],
  ["LVH", "lunarOrbit", "long", "Long (30 days-1 year)"],
  ["DSJH", "lunarSurface", "short", "Short (<30 days)"],
  ["PL", "lunarSurface", "long", "Long (30 days-1 year)"],
  ["MarsPrep", "mars", "preparatory", "Preparatory (<1 year)"],
  ["MarsPlanet", "mars", "planetary", "Mars Planetary (730-1224 days)"],
];
const COLOURS = { "#008000": "green", "#FFFF00": "yellow", "#CC2929": "red" };

const cacheArg = process.argv.indexOf("--cache");
const cache = cacheArg > 0 ? resolve(process.argv[cacheArg + 1]) : null;
if (cache) mkdirSync(cache, { recursive: true });
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "hrr-risks.js");

const text = (html) => html.replace(/<br\s*\/?>/gi, " ").replace(/<[^>]+>/g, "").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/\s+/g, " ").trim();

function cell(html, id) {
  const m = html.match(new RegExp(`<td id="ctl00_content_td${id}"([^>]*)>([\\s\\S]*?)</td>`));
  if (!m) return null;
  const bg = (m[1].match(/background-color:\s*(#[0-9A-Fa-f]{6})/) || [])[1];
  return { value: text(m[2]), colour: bg ? COLOURS[bg.toUpperCase()] || bg : null };
}

function side(html, key, which) {
  const lxc = cell(html, `${key}${which}LxC`);
  const disp = cell(html, `${key}${which}Disposition`);
  if (!lxc && !disp) throw new Error(`cell ${key}${which} not found`);
  const m = lxc && lxc.value.match(/^(\d)\s*x\s*(\d)$/i);
  return {
    l: m ? Number(m[1]) : null,
    c: m ? Number(m[2]) : null,
    colour: m && lxc.colour ? lxc.colour : null,
    disposition: (disp && disp.value) || (lxc && !m && lxc.value) || null,
  };
}

const risks = [];
const fetched = new Date().toISOString().slice(0, 10);
for (const id of IDS) {
  const url = `https://humanresearchroadmap.nasa.gov/risks/?i=${id}`;
  const file = cache && join(cache, `risk-${id}.html`);
  let html;
  if (file && existsSync(file)) html = readFileSync(file, "utf8");
  else {
    const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0 (compatible; research-script)" } });
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    html = await res.text();
    if (file) writeFileSync(file, html);
  }
  const ratings = {};
  for (const [key, drm, duration, label] of CELLS) {
    ratings[drm] = ratings[drm] || {};
    ratings[drm][duration] = { duration: label, ops: side(html, key, "Ops"), lth: side(html, key, "LTH") };
  }
  const approved = (text(html).match(/last approved by the Human System Risk Board in\s*([\d/]+)/) || [])[1] || null;
  const published = (text(html).match(/Last Published:\s*(\d\d\/\d\d\/\d\d)/) || [])[1] || null;
  const shortTitle = (text(html).match(/Short Title:\s*(.+?)\s*Last Published:/) || [])[1] || null;
  const title = text((html.match(/<title>([\s\S]*?)<\/title>/) || [, ""])[1]).replace(/^HRR - Risk - /, "") || null;
  if (!title || !shortTitle || !published) throw new Error(`${url}: title, short title or published date not found`);
  risks.push({ id, title, short: shortTitle, url, published, boardApproved: approved, fetched, ratings });
  console.log(`${String(id).padStart(3)} ${String(shortTitle).padEnd(22)} ${published} | ` + CELLS.map(([, d, k]) => { const r = ratings[d][k]; const f = (x) => (x.l ? `${x.l}x${x.c}` : "-"); return `${f(r.ops)}/${f(r.lth)}`; }).join(" "));
}

const header = [
  "// NASA Human Research Roadmap: the 22 human system risks and their ratings per mission type.",
  "// Generated by tools/fetch-hrr.mjs from https://humanresearchroadmap.nasa.gov/risks/ . Do not edit by hand.",
  "// l x c = likelihood x consequence as rated by the NASA Human System Risk Board; colour is the page's cell colour.",
  "// ops = in-mission operations, lth = long-term health. null l/c = NASA gives no rating for that mission.",
  "",
].join("\n");
writeFileSync(out, header + "export default " + JSON.stringify({ source: "https://humanresearchroadmap.nasa.gov/risks/", risks }, null, 2) + ";\n");
console.log(`\nwrote ${risks.length} risks to ${out}`);
